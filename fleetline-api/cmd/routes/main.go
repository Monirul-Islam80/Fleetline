// Command routes prints every API route as a Markdown table: go run ./cmd/routes > ROUTES.md
package main

import (
	"fmt"
	"sort"
	"strings"

	"github.com/gin-gonic/gin"

	"fleetline/api/internal/api"
	"fleetline/api/internal/config"
)

func main() {
	engine := api.New(config.Load(), nil, nil, nil, nil, nil).Handler().(*gin.Engine)
	routes := engine.Routes()
	sort.SliceStable(routes, func(a, b int) bool {
		if routes[a].Path != routes[b].Path {
			return routes[a].Path < routes[b].Path
		}
		return routes[a].Method < routes[b].Method
	})
	fmt.Println("# API routes\n\nGenerated by `go run ./cmd/routes`. Base path `/api/v1`.\n\n| Group | Method | Path |\n| --- | --- | --- |")
	for _, r := range routes {
		path := strings.TrimPrefix(r.Path, "/api/v1")
		group := strings.SplitN(strings.TrimPrefix(path, "/"), "/", 2)[0]
		if !strings.HasPrefix(r.Path, "/api/v1") {
			group = "(health)"
		}
		fmt.Printf("| %s | %s | `%s` |\n", group, r.Method, path)
	}
	fmt.Printf("\n%d routes.\n", len(routes))
}
